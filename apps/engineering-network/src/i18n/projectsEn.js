/**
 * Returns localized project entity for a given locale
 * Falls back to English for Thai and unsupported locales (NEVER silent Chinese)
 */
export function getLocalizedProject(proj, locale) {
  if (!proj) return proj;
  if (locale === 'zh') return proj;
  const key = proj.id || proj.code;
  const en = PROJECTS_EN[key] || PROJECTS_EN[proj.code] || PROJECTS_EN[proj.id];
  if (!en) return proj;

  return {
    ...proj,
    name: en.name || proj.name,
    shortName: en.shortName || proj.shortName,
    type: en.type || proj.type,
    sector: en.sector || proj.sector,
    location: en.location || proj.location,
    region: en.region || proj.region,
    status: en.status || proj.status,
    currentPhase: en.currentPhase || proj.currentPhase,
    investmentScale: en.investmentScale || proj.investmentScale,
    grossFloorArea: en.grossFloorArea || proj.grossFloorArea,
    plannedCycle: en.plannedCycle || proj.plannedCycle,
    summary: en.summary || proj.summary,
    verificationScore: en.verificationScore || proj.verificationScore,
    sourceAndVersion: en.sourceAndVersion || proj.sourceAndVersion,
  };
}

